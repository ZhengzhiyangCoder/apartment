import { test, expect, type Page } from '@playwright/test'

async function login(page: Page, username = 'system_admin') {
  await page.goto('/login')
  await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill('DemoPass2026!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('link', { name: '个人资料', exact: true })).toBeVisible()
}
async function post(page: Page, path: string, data: object) {
  const csrf = await (await page.request.get('/api/auth/csrf')).json()
  return page.request.post(path, { headers: { [csrf.headerName]: csrf.token }, data })
}
async function create(page: Page, path: string, data: object) {
  const response = await post(page, path, data)
  expect(response.status(), await response.text()).toBe(201)
  return response.json()
}
async function fixtures(page: Page, prefix: string) {
  const user = await create(page, '/api/identity/accounts', { username: prefix, displayName: '模拟入住学生', role: 'STUDENT', password: 'DemoPass2026!' })
  const student = await create(page, '/api/housing/students', { userId: user.id, studentNo: prefix, fullName: '模拟入住学生', college: '模拟学院', major: '模拟专业', className: '模拟班级' })
  const building = await create(page, '/api/housing/buildings', { name: prefix })
  const room = await create(page, '/api/housing/rooms', { buildingId: building.id, roomNo: '101', floor: 1 })
  const bed = await create(page, '/api/housing/beds', { roomId: room.id, bedNo: '01' })
  return { user, student, building, room, bed }
}

test('页面办理入住，学生在独立会话刷新后看到本人住宿', async ({ page, browser }) => {
  const prefix = `resident_${page.viewportSize()!.width}`
  await login(page)
  const fixture = await fixtures(page, prefix)
  const studentContext = await browser.newContext({ viewport: page.viewportSize()! })
  try {
    const studentPage = await studentContext.newPage()
    await login(studentPage, prefix)
    await studentPage.getByRole('link', { name: '我的住宿', exact: true }).click({ timeout: 5000 })
    await expect(studentPage.getByRole('heading', { name: '尚未入住', exact: true })).toBeVisible()
    await page.getByRole('link', { name: '入住办理', exact: true }).click()
    await page.getByRole('button', { name: '办理入住', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('搜索入住学生').fill(prefix)
    await dialog.getByRole('group', { name: '入住学生', exact: true }).getByRole('button', { name: '查找', exact: true }).click()
    await dialog.getByLabel('入住学生', { exact: true }).selectOption({ label: `${prefix} · 模拟入住学生` })
    await dialog.getByLabel('搜索空床位').fill(prefix)
    await dialog.getByRole('group', { name: '空床位', exact: true }).getByRole('button', { name: '查找', exact: true }).click()
    await dialog.getByLabel('空床位', { exact: true }).selectOption({ label: `${prefix} · 101 · 01 号床` })
    await dialog.getByRole('button', { name: '确认入住', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await studentPage.getByRole('button', { name: '刷新住宿', exact: true }).click()
    await expect(studentPage.getByTestId('current-residency')).toContainText(prefix)
    await expect(studentPage.getByTestId('current-residency')).toContainText('01 号床')
    await studentPage.screenshot({ path: `../output/playwright/task04-my-residency-${page.viewportSize()!.width}.png`, fullPage: true })
    expect(await studentPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    const otherRoom = await create(page, '/api/housing/rooms', { buildingId: fixture.building.id, roomNo: '202', floor: 2 })
    await create(page, '/api/housing/beds', { roomId: otherRoom.id, bedNo: '02' })
    await page.getByLabel('搜索住宿').fill(prefix)
    await page.getByRole('button', { name: '查询', exact: true }).click()
    const row = page.getByRole('row').filter({ hasText: prefix })
    await row.getByRole('button', { name: '调寝', exact: true }).click()
    await dialog.getByLabel('搜索空床位').fill(prefix)
    await dialog.getByRole('button', { name: '查找', exact: true }).click()
    await dialog.getByLabel('空床位', { exact: true }).selectOption({ label: `${prefix} · 202 · 02 号床` })
    await dialog.getByLabel('办理说明').fill('模拟申请调寝')
    await page.route('**/api/housing/residencies/*/transfer', route => route.abort('failed'))
    await dialog.getByRole('button', { name: '确认调寝', exact: true }).click()
    await expect(dialog.getByRole('alert')).toContainText('暂时无法连接服务')
    await expect(dialog.getByLabel('办理说明')).toHaveValue('模拟申请调寝')
    await page.screenshot({ path: `../output/playwright/task04-transfer-error-${page.viewportSize()!.width}.png` })
    await page.unroute('**/api/housing/residencies/*/transfer')
    await dialog.getByRole('button', { name: '确认调寝', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await expect(row).toContainText('202 · 02 号床')
    await studentPage.getByRole('button', { name: '刷新住宿', exact: true }).click()
    await expect(studentPage.getByTestId('current-residency')).toContainText('202')
    await expect(studentPage.getByTestId('current-residency')).toContainText('02 号床')
    await row.getByRole('button', { name: '退宿', exact: true }).click()
    await dialog.getByLabel('办理说明').fill('模拟毕业退宿')
    await dialog.getByRole('button', { name: '确认退宿', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await expect(page.getByText('暂无符合条件的住宿记录。')).toBeVisible()
    await studentPage.reload()
    await expect(studentPage.getByRole('heading', { name: '尚未入住', exact: true })).toBeVisible()
    await studentPage.screenshot({ path: `../output/playwright/task04-not-resident-${page.viewportSize()!.width}.png`, fullPage: true })
    await page.getByLabel('住宿状态').selectOption('false')
    await page.getByRole('button', { name: '查询', exact: true }).click()
    await expect(page.getByRole('row')).toHaveCount(3)
    await expect(page.getByRole('table')).toContainText('模拟申请调寝')
    await expect(page.getByRole('table')).toContainText('模拟毕业退宿')
    await page.screenshot({ path: `../output/playwright/task04-history-${page.viewportSize()!.width}.png`, fullPage: true })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()

  } finally { await studentContext.close() }
})

test('旧窗口调寝冲突保留说明，入住关联资料停用被拒', async ({ page }) => {
  const prefix = `stale_${page.viewportSize()!.width}`
  await login(page)
  const fixture = await fixtures(page, prefix)
  const residence = await create(page, '/api/housing/residencies', { studentId: fixture.student.id, bedId: fixture.bed.id })
  const secondBed = await create(page, '/api/housing/beds', { roomId: fixture.room.id, bedNo: '02' })
  const thirdBed = await create(page, '/api/housing/beds', { roomId: fixture.room.id, bedNo: '03' })
  await page.goto('/housing')
  await page.getByLabel('搜索资料').fill(prefix)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await page.getByRole('row').filter({ hasText: prefix }).getByRole('button', { name: '停用', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: '确认停用' }).click()
  await expect(dialog.getByRole('alert')).toContainText('存在当前入住')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('link', { name: '入住办理', exact: true }).click()
  await page.getByLabel('搜索住宿').fill(prefix)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: prefix })
  await row.getByRole('button', { name: '调寝', exact: true }).click()
  await dialog.getByLabel('搜索空床位').fill(prefix)
  await dialog.getByRole('button', { name: '查找', exact: true }).click()
  await dialog.getByLabel('空床位', { exact: true }).selectOption(String(secondBed.id))
  await dialog.getByLabel('办理说明').fill('保留这段输入')
  expect((await post(page, `/api/housing/residencies/${residence.id}/transfer`, { bedId: thirdBed.id, note: '另一窗口先办理' })).status()).toBe(200)
  await dialog.getByRole('button', { name: '确认调寝', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('该住宿关系已结束')
  await expect(dialog.getByLabel('办理说明')).toHaveValue('保留这段输入')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(row).toContainText('03 号床')
})

test('住宿历史支持查询分页与失败重试', async ({ page }) => {
  const prefix = `history_${page.viewportSize()!.width}`
  await login(page)
  const fixture = await fixtures(page, prefix)
  for (let i = 0; i < 11; i++) {
    const current = await create(page, '/api/housing/residencies', { studentId: fixture.student.id, bedId: fixture.bed.id })
    expect((await post(page, `/api/housing/residencies/${current.id}/checkout`, { note: `模拟第 ${i + 1} 次退宿` })).status()).toBe(200)
  }
  await page.goto('/residencies')
  await page.getByLabel('搜索住宿').fill(prefix)
  await page.getByLabel('住宿状态').selectOption('false')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.getByRole('row')).toHaveCount(11)
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page.getByRole('row')).toHaveCount(2)
  await expect(page.getByRole('table')).toContainText('模拟第 1 次退宿')
  await page.route('**/api/housing/residencies?**', route => route.abort('failed'))
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('暂时无法连接服务')
  await expect(page.getByLabel('搜索住宿')).toHaveValue(prefix)
  await page.unroute('**/api/housing/residencies?**')
  await page.getByRole('button', { name: '重新加载', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByLabel('搜索住宿').fill('没有这名学生')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.getByText('暂无符合条件的住宿记录。')).toBeVisible()
})

test('各角色住宿入口和直接访问均遵守权限，学生断网不显示过时住宿', async ({ page }) => {
  for (const username of ['dorm_manager', 'maintainer', 'student']) {
    await login(page, username)
    await expect(page.getByRole('link', { name: '入住办理', exact: true })).toHaveCount(0)
    await page.goto('/residencies')
    await expect(page.getByRole('heading', { name: '此页面暂不可访问' })).toBeVisible()
    if (username === 'student') {
      await page.getByRole('link', { name: '我的住宿', exact: true }).click()
      await page.route('**/api/housing/my-residency', route => route.abort('failed'))
      await page.getByRole('button', { name: '刷新住宿', exact: true }).click()
      await expect(page.getByRole('alert')).toContainText('暂时无法连接服务')
      await expect(page.getByRole('heading', { name: '尚未入住', exact: true })).toHaveCount(0)
      await page.unroute('**/api/housing/my-residency')
      await page.getByRole('button', { name: '重新加载', exact: true }).click()
      await expect(page.getByRole('alert')).toHaveCount(0)
    } else {
      await expect(page.getByRole('link', { name: '我的住宿', exact: true })).toHaveCount(0)
      await page.goto('/my-residency')
      await expect(page.getByRole('heading', { name: '此页面暂不可访问' })).toBeVisible()
    }
    await page.getByRole('button', { name: '退出登录', exact: true }).click()
    await expect(page.getByRole('heading', { name: '登录栖居' })).toBeVisible()
  }
})
