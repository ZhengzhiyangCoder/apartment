import { test, expect, type Page } from '@playwright/test'

async function login(page: Page, username: string) {
  await page.goto('/login')
  await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill('DemoPass2026!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('link', { name: '个人资料', exact: true })).toBeVisible()
}
async function post(page: Page, path: string, data: object) {
  const csrf = await (await page.request.get('/api/auth/csrf')).json()
  return page.request.post(path, { headers: { [csrf.headerName]: csrf.token }, data })
}
async function create(page: Page, path: string, data: object) {
  const response = await post(page, path, data)
  expect(response.status(), await response.text()).toBe(201)
  return response.json()
}
async function fixtures(page: Page, username: string) {
  const user = await create(page, '/api/identity/accounts', { username, displayName: '模拟报修学生', role: 'STUDENT', password: 'DemoPass2026!' })
  const student = await create(page, '/api/housing/students', { userId: user.id, studentNo: username, fullName: '模拟报修学生', college: '模拟学院', major: '模拟专业', className: '模拟班级' })
  const building = await create(page, '/api/housing/buildings', { name: username })
  const room = await create(page, '/api/housing/rooms', { buildingId: building.id, roomNo: '101', floor: 1 })
  const bed = await create(page, '/api/housing/beds', { roomId: room.id, bedNo: '01' })
  const residency = await create(page, '/api/housing/residencies', { studentId: student.id, bedId: bed.id })
  return { user, student, building, room, bed, residency }
}
async function photo(page: Page) {
  const data = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 32; c.height = 32; const ctx = c.getContext('2d')!; ctx.fillStyle = '#62798d'; ctx.fillRect(0, 0, 32, 32); return c.toDataURL('image/png').split(',')[1]! })
  return { name: '模拟水龙头.png', mimeType: 'image/png', buffer: Buffer.from(data, 'base64') }
}

test('学生真实上传，失败保留文字和图片，调寝退宿后历史与取消可用', async ({ page, browser }) => {
  await login(page, 'system_admin')
  const prefix = `repair_${page.viewportSize()!.width}`
  const f = await fixtures(page, prefix)
  const context = await browser.newContext({ viewport: page.viewportSize()! })
  try {
    const student = await context.newPage(); await login(student, prefix)
    await student.getByRole('link', { name: '我的报修', exact: true }).click({ timeout: 5000 })
    await student.getByRole('button', { name: '新建报修', exact: true }).click()
    const form = student.getByRole('dialog', { name: '新建报修', exact: true })
    await form.getByLabel('问题类型').selectOption('PLUMBING')
    await form.getByLabel('问题描述').fill('模拟水龙头持续滴水，请检查阀门')
    await form.getByLabel('现场图片').setInputFiles(await photo(student))
    await student.route('**/api/repairs', route => route.abort('failed'))
    await form.getByRole('button', { name: '提交报修', exact: true }).click()
    await expect(form.getByRole('alert')).toContainText('暂时无法连接服务')
    await expect(form.getByLabel('问题描述')).toHaveValue('模拟水龙头持续滴水，请检查阀门')
    await expect(form.getByText('模拟水龙头.png', { exact: true })).toBeVisible()
    await student.screenshot({ animations: 'disabled', path: `../output/playwright/task05-upload-error-${page.viewportSize()!.width}.png` })
    await student.unroute('**/api/repairs')
    await form.getByRole('button', { name: '提交报修', exact: true }).click()
    await expect(form).not.toBeVisible()
    await expect(student.getByRole('table')).toContainText('待分配')
    await student.getByRole('button', { name: '查看详情', exact: true }).click()
    const detail = student.getByRole('dialog', { name: /工单详情/ })
    await expect(detail.getByText('提交报修', { exact: true })).toBeVisible()
    await expect(detail.getByRole('img', { name: '报修图片 1' })).toBeVisible()
    await expect.poll(() => detail.getByRole('img', { name: '报修图片 1' }).evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(32)
    await student.screenshot({ animations: 'disabled', path: `../output/playwright/task05-detail-${page.viewportSize()!.width}.png` })
    await detail.getByRole('button', { name: '关闭详情', exact: true }).click()
    await expect(detail).not.toBeVisible()
    const newRoom = await create(page, '/api/housing/rooms', { buildingId: f.building.id, roomNo: '202', floor: 2 })
    const newBed = await create(page, '/api/housing/beds', { roomId: newRoom.id, bedNo: '02' })
    const movedResponse = await post(page, `/api/housing/residencies/${f.residency.id}/transfer`, { bedId: newBed.id, note: '模拟调寝' })
    expect(movedResponse.status()).toBe(200); const moved = await movedResponse.json()
    await student.reload()
    await expect(student.getByTestId('repair-residency')).toContainText('202')
    await expect(student.getByRole('table')).toContainText('101')
    expect((await post(page, `/api/housing/residencies/${moved.id}/checkout`, { note: '模拟退宿' })).status()).toBe(200)
    await student.reload()
    await expect(student.getByText('尚未入住，暂不能新建报修。本人历史工单仍可查看。')).toBeVisible()
    await expect(student.getByRole('button', { name: '新建报修', exact: true })).toBeDisabled()
    await student.getByRole('button', { name: '查看详情', exact: true }).click()
    await detail.getByLabel('取消原因').fill('模拟误报，已自行解决')
    await detail.getByRole('button', { name: '确认取消工单', exact: true }).click()
    await expect(detail.getByText('已取消', { exact: true }).first()).toBeVisible()
    await expect(detail.getByText('模拟误报，已自行解决', { exact: true })).toBeVisible()
    await student.screenshot({ animations: 'disabled', path: `../output/playwright/task05-cancelled-${page.viewportSize()!.width}.png` })
    expect(await student.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await detail.getByRole('button', { name: '关闭详情', exact: true }).click()
    await expect(detail).not.toBeVisible()
    await page.goto('/repairs')
    await page.getByLabel('搜索报修').fill(prefix)
    await page.getByRole('button', { name: '查询', exact: true }).click()
    await expect(page.getByRole('table')).toContainText('已取消')
  } finally { await context.close() }
})

test('管理角色查询分页、图片失败重试和旧窗口取消冲突', async ({ page, browser }) => {
  await login(page, 'system_admin'); const prefix = `repair_mgr_${page.viewportSize()!.width}`
  await fixtures(page, prefix)
  const context = await browser.newContext({ viewport: page.viewportSize()! })
  try {
    const other = await context.newPage(); await login(other, prefix)
    const upload = await photo(other)
    for (let i = 0; i < 11; i++) {
      const csrf = await (await other.request.get('/api/auth/csrf')).json()
      const response = await other.request.post('/api/repairs', { headers: { [csrf.headerName]: csrf.token }, multipart: { category: 'PLUMBING', description: `模拟分页报修 ${i}`, requestId: crypto.randomUUID(), images: upload } })
      expect(response.status(), await response.text()).toBe(201)
    }
    expect((await post(other, '/api/auth/logout', {})).status()).toBe(204)
    await login(other, 'dorm_manager'); await other.getByRole('link', { name: '报修管理', exact: true }).click()
    await other.getByLabel('搜索报修').fill(prefix); await other.getByRole('button', { name: '查询', exact: true }).click()
    await expect(other.getByText('共 11 条记录', { exact: true })).toBeVisible()
    await other.getByRole('button', { name: '下一页', exact: true }).click()
    await expect(other.getByRole('table')).toContainText('模拟分页报修 0')
    await expect(other.getByRole('row')).toHaveCount(2)
    await other.route('**/api/repairs/*/images/*', route => route.abort('failed'))
    await other.getByRole('button', { name: '查看详情', exact: true }).click()
    const detail = other.getByRole('dialog', { name: /工单详情/ })
    await expect(detail.getByText('图片加载失败。')).toBeVisible()
    await other.unroute('**/api/repairs/*/images/*')
    await detail.getByRole('button', { name: '重试图片 1' }).click()
    await expect.poll(() => detail.getByRole('img', { name: '报修图片 1' }).evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(32)
    const rows = await (await page.request.get(`/api/repairs?q=${prefix}&size=100`)).json()
    const oldest = rows.items.at(-1)
    await detail.getByLabel('取消原因').fill('宿管核实为重复报修')
    expect((await post(page, `/api/repairs/${oldest.id}/cancel`, { reason: '管理员先行取消' })).status()).toBe(200)
    await detail.getByRole('button', { name: '确认取消工单', exact: true }).click()
    await expect(detail.getByRole('alert')).toContainText('工单状态已变化')
    await expect(detail.getByLabel('取消原因')).toHaveValue('宿管核实为重复报修')
    await other.screenshot({ animations: 'disabled', path: `../output/playwright/task05-cancel-conflict-${page.viewportSize()!.width}.png` })
    await detail.getByRole('button', { name: '刷新详情' }).click()
    await expect(detail.getByText('管理员先行取消', { exact: true })).toBeVisible()
    await expect(detail.getByRole('button', { name: '确认取消工单', exact: true })).not.toBeVisible()
    await detail.getByRole('button', { name: '关闭详情', exact: true }).click()
    await expect(detail).not.toBeVisible()
    await other.getByLabel('工单状态').selectOption('PENDING_ASSIGNMENT'); await other.getByRole('button', { name: '查询', exact: true }).click()
    await expect(other.getByText('共 10 条记录', { exact: true })).toBeVisible()
    await other.getByRole('button', { name: '查看详情', exact: true }).first().click()
    await detail.getByLabel('取消原因').fill('宿管确认误报')
    await detail.getByRole('button', { name: '确认取消工单', exact: true }).click()
    await expect(detail.getByText('宿管确认误报', { exact: true })).toBeVisible()
    await detail.getByRole('button', { name: '关闭详情', exact: true }).click()
    await expect(detail).not.toBeVisible()
    await expect(other.getByText('共 9 条记录', { exact: true })).toBeVisible()
    await other.screenshot({ animations: 'disabled', path: `../output/playwright/task05-management-${page.viewportSize()!.width}.png`, fullPage: true })
    expect(await other.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    await other.getByLabel('搜索报修').fill('没有此报修')
    await other.getByRole('button', { name: '查询', exact: true }).click()
    await expect(other.getByText('暂无符合条件的报修工单。')).toBeVisible()
    await other.route('**/api/repairs?**', route => route.abort('failed'))
    await other.getByRole('button', { name: '查询', exact: true }).click()
    await expect(other.getByRole('alert')).toContainText('暂时无法连接服务')
    await other.unroute('**/api/repairs?**'); await other.getByRole('button', { name: '重新加载' }).click()
    await expect(other.getByText('暂无符合条件的报修工单。')).toBeVisible()
  } finally { await context.close() }
})

test('伪装图片被拒后可恢复，维修角色不能直访管理页面', async ({ page, browser }) => {
  await login(page, 'system_admin'); const prefix = `repair_invalid_${page.viewportSize()!.width}`
  await fixtures(page, prefix)
  const context = await browser.newContext({ viewport: page.viewportSize()! })
  try {
    const student = await context.newPage(); await login(student, prefix); await student.goto('/repairs')
    await student.getByRole('button', { name: '新建报修' }).click()
    const form = student.getByRole('dialog', { name: '新建报修', exact: true })
    await form.getByLabel('问题描述').fill('模拟伪装图片校验')
    await form.getByLabel('现场图片').setInputFiles({ name: 'fake.png', mimeType: 'image/png', buffer: Buffer.from('<html>not a picture</html>') })
    await form.getByRole('button', { name: '提交报修', exact: true }).click()
    await expect(form.getByRole('alert')).toContainText('图片内容无效')
    await expect(form.getByLabel('问题描述')).toHaveValue('模拟伪装图片校验')
    await form.getByLabel('现场图片').setInputFiles(await photo(student))
    await form.getByRole('button', { name: '提交报修', exact: true }).click()
    await expect(form).not.toBeVisible()
    await expect(student.getByRole('table')).toContainText('模拟伪装图片校验')
    expect((await post(student, '/api/auth/logout', {})).status()).toBe(204)
    await login(student, 'maintainer')
    await expect(student.getByRole('link', { name: '报修管理', exact: true })).not.toBeVisible()
    await expect(student.getByRole('link', { name: '我的报修', exact: true })).not.toBeVisible()
    await student.goto('/repairs'); await expect(student).toHaveURL(/\/forbidden$/)
  } finally { await context.close() }
})
