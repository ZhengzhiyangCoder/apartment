import { test, expect, type Page } from '@playwright/test'

async function login(page: Page, username: string, password = 'DemoPass2026!') {
  await page.goto('/login')
  await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
}

test('系统管理员创建账号，新账号可登录，重置密码后禁用并恢复', async ({ page, browser }) => {
  const username = `browser_${page.viewportSize()!.width}`
  await login(page, 'system_admin')
  await page.getByRole('link', { name: '账号管理', exact: true }).click({ timeout: 5000 })
  await expect(page.getByRole('heading', { name: '账号管理', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '创建账号', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('登录账号', { exact: true }).fill(username)
  await dialog.getByLabel('姓名', { exact: true }).fill('浏览器模拟学生')
  await dialog.getByLabel('角色', { exact: true }).selectOption('STUDENT')
  await dialog.getByLabel('初始密码', { exact: true }).fill('CreatedPass2026!')
  await dialog.getByRole('button', { name: '确认创建', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByLabel('搜索账号或姓名').fill(username)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: username })
  await expect(row).toContainText('浏览器模拟学生')
  await page.screenshot({ path: `../output/playwright/task02-accounts-${page.viewportSize()!.width}.png`, fullPage: true, animations: 'disabled' })
  const other = await browser.newContext({ viewport: page.viewportSize()! })
  const student = await other.newPage()
  try {
    await login(student, username, 'CreatedPass2026!')
    await expect(student.getByRole('heading', { name: '学生工作台' })).toBeVisible()
    await row.getByRole('button', { name: '重置密码' }).click()
    await dialog.getByLabel('新密码', { exact: true }).fill('ResetPass2026!')
    await dialog.getByLabel('确认新密码', { exact: true }).fill('ResetPass2026!')
    await dialog.getByRole('button', { name: '确认重置' }).click()
    await expect(dialog).not.toBeVisible()
    await student.reload()
    await expect(student.getByRole('heading', { name: '登录栖居' })).toBeVisible()
    await login(student, username, 'ResetPass2026!')
    await expect(student.getByRole('heading', { name: '学生工作台' })).toBeVisible()
    await row.getByRole('button', { name: '变更角色' }).click()
    await dialog.getByLabel('角色', { exact: true }).selectOption('MAINTAINER')
    await dialog.getByRole('button', { name: '保存角色' }).click()
    await expect(dialog).not.toBeVisible()
    await student.reload()
    await expect(student.getByRole('heading', { name: '登录栖居' })).toBeVisible()
    await login(student, username, 'ResetPass2026!')
    await expect(student.getByRole('heading', { name: '维修人员工作台' })).toBeVisible()
    await row.getByRole('button', { name: '禁用', exact: true }).click()
    await expect(dialog).toBeVisible()
    await expect(dialog).toContainText('已有登录将失效')
    await page.screenshot({ path: `../output/playwright/task02-disable-${page.viewportSize()!.width}.png`, fullPage: true, animations: 'disabled' })
    await dialog.getByRole('button', { name: '确认禁用' }).click()
    await expect(dialog).not.toBeVisible()
    await expect(row).toContainText('已停用')
    await student.reload()
    await expect(student.getByRole('heading', { name: '登录栖居' })).toBeVisible()
    await login(student, username, 'ResetPass2026!')
    await expect(student.getByRole('alert')).toContainText('账号或密码错误，或账号已停用')
    await row.getByRole('button', { name: '启用', exact: true }).click()
    await dialog.getByRole('button', { name: '确认启用' }).click()
    await expect(dialog).not.toBeVisible()
    await login(student, username, 'ResetPass2026!')
    await expect(student.getByRole('heading', { name: '维修人员工作台' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  } finally { await other.close() }
})


test('创建失败保留输入，可恢复重试，并发变更显示冲突', async ({ page }) => {
  await login(page, 'system_admin')
  await page.getByRole('link', { name: '账号管理', exact: true }).click()
  await page.getByRole('button', { name: '创建账号', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('登录账号', { exact: true }).fill('system_admin')
  await dialog.getByLabel('姓名', { exact: true }).fill('失败恢复模拟账号')
  await dialog.getByLabel('初始密码', { exact: true }).fill('CreatedPass2026!')
  await dialog.getByRole('button', { name: '确认创建' }).click()
  await expect(dialog.getByRole('alert')).toContainText('账号已存在')
  await expect(dialog.getByLabel('初始密码', { exact: true })).toHaveValue('CreatedPass2026!')
  const username = `recover_${page.viewportSize()!.width}`
  await dialog.getByLabel('登录账号', { exact: true }).fill(username)
  await page.route('**/api/identity/accounts', route => route.abort('failed'))
  await dialog.getByRole('button', { name: '确认创建' }).click()
  await expect(dialog.getByRole('alert')).toContainText('暂时无法连接服务')
  await expect(dialog.getByLabel('姓名', { exact: true })).toHaveValue('失败恢复模拟账号')
  await page.screenshot({ path: `../output/playwright/task02-create-${page.viewportSize()!.width}.png`, animations: 'disabled' })
  await page.unroute('**/api/identity/accounts')
  await dialog.getByRole('button', { name: '确认创建' }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByLabel('搜索账号或姓名').fill(username)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: username })
  await row.getByRole('button', { name: '变更角色' }).click()
  await dialog.getByLabel('角色', { exact: true }).selectOption('DORM_MANAGER')
  const account = (await (await page.request.get(`/api/identity/accounts?q=${username}`)).json()).items[0]
  const csrf = await (await page.request.get('/api/auth/csrf')).json()
  expect((await page.request.post(`/api/identity/accounts/${account.id}/role`, { headers: { [csrf.headerName]: csrf.token }, data: { role: 'MAINTAINER', version: account.version } })).status()).toBe(200)
  await dialog.getByRole('button', { name: '保存角色' }).click()
  await expect(dialog.getByRole('alert')).toContainText('账号已被更新')
  await expect(dialog.getByLabel('角色', { exact: true })).toHaveValue('DORM_MANAGER')
  await dialog.getByRole('button', { name: '取消' }).click()
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(row).toContainText('维修人员')
})

test('非系统管理员没有管理入口且直接访问被拒绝', async ({ page }) => {
  for (const username of ['dorm_manager', 'student', 'maintainer']) {
    await login(page, username)
    await expect(page.getByRole('link', { name: '个人资料', exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: '账号管理', exact: true })).toHaveCount(0)
    await page.goto('/accounts')
    await expect(page.getByRole('heading', { name: '此页面暂不可访问' })).toBeVisible()
    expect((await page.request.get('/api/identity/accounts')).status()).toBe(403)
    await page.getByRole('button', { name: '退出登录', exact: true }).click()
    await expect(page.getByRole('heading', { name: '登录栖居' })).toBeVisible()
  }
})

test('筛选分页和最后一位系统管理员保护可操作', async ({ page }) => {
  test.setTimeout(60000)
  await login(page, 'system_admin')
  await page.getByRole('link', { name: '账号管理', exact: true }).click()
  await page.getByLabel('搜索账号或姓名').fill('system_admin')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'system_admin' }).getByRole('button', { name: '禁用', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '确认禁用' }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('先创建或启用另一位系统管理员')
  await page.getByRole('dialog').getByRole('button', { name: '取消' }).click()
  const prefix = `pages_${page.viewportSize()!.width}_`
  const csrf = await (await page.request.get('/api/auth/csrf')).json()
  for (let i = 0; i < 11; i++) {
    expect((await page.request.post('/api/identity/accounts', { headers: { [csrf.headerName]: csrf.token }, data: { username: `${prefix}${i}`, displayName: '分页模拟学生', role: 'STUDENT', password: 'CreatedPass2026!' } })).status()).toBe(201)
  }
  await page.getByLabel('搜索账号或姓名').fill(prefix)
  await page.getByLabel('角色筛选').selectOption('STUDENT')
  await page.getByLabel('状态筛选').selectOption('true')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.getByRole('row')).toHaveCount(11)
  await page.getByRole('button', { name: '下一页' }).click()
  await expect(page.getByRole('row')).toHaveCount(2)
  await page.getByRole('row').filter({ hasText: prefix }).getByRole('button', { name: '禁用', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '确认禁用' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByRole('row')).toHaveCount(11)
  await expect(page.getByRole('button', { name: '下一页' })).toBeDisabled()
  await page.getByLabel('搜索账号或姓名').fill('no_such_account')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.getByText('暂无符合条件的账号，请调整查询条件。')).toBeVisible()
})
