import { test, expect, type Page } from '@playwright/test'

async function login(page: Page, username: string) {
  await page.goto('/login'); await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill('DemoPass2026!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('link', { name: '个人资料', exact: true })).toBeVisible()
}
async function post(page: Page, path: string, data: object) {
  const csrf = await (await page.request.get('/api/auth/csrf')).json()
  return page.request.post(path, { headers: { [csrf.headerName]: csrf.token }, data })
}
async function fillDefinition(page: Page, name: string, weights = ['40', '30', '30']) {
  const form = page.getByRole('dialog', { name: /评分草稿/ })
  await form.getByLabel('方案名称', { exact: true }).fill(name)
  for (let i = 0; i < weights.length; i++) {
    if (await form.getByLabel(`维度名称 ${i + 1}`, { exact: true }).count() === 0) await form.getByRole('button', { name: '添加维度', exact: true }).click()
    await form.getByLabel(`维度名称 ${i + 1}`, { exact: true }).fill(['地面', '摆放', '整洁'][i]!)
    await form.getByLabel(`权重 ${i + 1}`, { exact: true }).fill(weights[i]!)
  }
  return form
}
async function search(page: Page, name: string) {
  await page.getByLabel('搜索方案', { exact: true }).fill(name)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.getByRole('table')).toContainText(name)
}
function definition(name: string) { return { name, threshold: 60, dimensions: [{ name: '地面', weight: 40 }, { name: '摆放', weight: 30 }, { name: '整洁', weight: 30 }] } }
async function create(page: Page, name: string) {
  const response = await post(page, '/api/hygiene/schemes', definition(name))
  expect(response.status(), await response.text()).toBe(201); return response.json()
}

test('权重精度、总额与重复维度有明确反馈，断网和编辑冲突保留输入', async ({ page }) => {
  test.setTimeout(60000)
  const name = `模拟恢复_${page.viewportSize()!.width}`
  await login(page, 'system_admin'); await page.goto('/schemes')
  await page.getByRole('button', { name: '新建评分草稿', exact: true }).click()
  const form = await fillDefinition(page, name, ['33.333', '33.33', '33.33'])
  await form.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('最多两位小数')
  await form.getByLabel('权重 1', { exact: true }).fill('33.33')
  await page.route('**/api/hygiene/schemes', route => route.abort('failed'))
  await form.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('暂时无法连接服务')
  await expect(form.getByLabel('方案名称', { exact: true })).toHaveValue(name)
  await expect(form.getByLabel('权重 3', { exact: true })).toHaveValue('33.33')
  await page.screenshot({ animations: 'disabled', path: `../output/playwright/task07-form-error-${page.viewportSize()!.width}.png` })
  await page.unroute('**/api/hygiene/schemes'); await form.getByRole('button', { name: '保存草稿', exact: true }).click(); await expect(form).not.toBeVisible()
  await search(page, name); await page.getByRole('button', { name: '启用', exact: true }).click()
  const activation = page.getByRole('dialog', { name: '启用评分方案', exact: true })
  await activation.getByRole('button', { name: '确认启用', exact: true }).click()
  await expect(activation.getByRole('alert')).toContainText('权重合计必须等于100%')
  await activation.getByRole('button', { name: '返回', exact: true }).click(); await expect(activation).not.toBeVisible()
  await page.getByRole('button', { name: '编辑草稿', exact: true }).click()
  const edit = page.getByRole('dialog', { name: '编辑评分草稿', exact: true })
  await edit.getByLabel('维度名称 2', { exact: true }).fill('地面')
  await edit.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(edit.getByRole('alert')).toContainText('维度名称不能重复')
  await edit.getByLabel('维度名称 2', { exact: true }).fill('摆放')
  await edit.getByLabel('权重 3', { exact: true }).fill('33.34')
  const data = await (await page.request.get(`/api/hygiene/schemes?q=${encodeURIComponent(name)}`)).json(); const draft = data.items[0]
  expect((await post(page, `/api/hygiene/schemes/${draft.id}`, { version: draft.version, definition: definition(`${name}_他人更新`) })).status()).toBe(200)
  await edit.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(edit.getByRole('alert')).toContainText('方案已变化')
  await expect(edit.getByLabel('权重 3', { exact: true })).toHaveValue('33.34')
  await page.screenshot({ animations: 'disabled', path: `../output/playwright/task07-draft-conflict-${page.viewportSize()!.width}.png` })
  await edit.getByRole('button', { name: '载入最新草稿（替换输入）', exact: true }).click()
  await expect(edit.getByLabel('方案名称', { exact: true })).toHaveValue(`${name}_他人更新`)
  await edit.getByRole('button', { name: '删除维度 3', exact: true }).click()
  await edit.getByLabel('权重 1', { exact: true }).fill('60'); await edit.getByLabel('权重 2', { exact: true }).fill('40')
  await edit.getByRole('button', { name: '保存草稿', exact: true }).click(); await expect(edit).not.toBeVisible()
  await expect(page.getByRole('table')).toContainText('2个维度')
  await page.getByRole('button', { name: '编辑草稿', exact: true }).click()
  await edit.getByLabel('整改阈值', { exact: true }).fill('70')
  const latest = await (await page.request.get(`/api/hygiene/schemes?q=${encodeURIComponent(name)}`)).json()
  expect((await post(page, `/api/hygiene/schemes/${latest.items[0].id}/activate`, { version: latest.items[0].version, activeId: latest.active?.id ?? 0 })).status()).toBe(200)
  await edit.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(edit.getByRole('alert')).toContainText('已启用或历史版本不可修改')
  await edit.getByRole('button', { name: '载入最新草稿（替换输入）', exact: true }).click()
  await expect(edit.getByRole('alert')).toContainText('此版本已启用并固定')
  await expect(edit.getByLabel('整改阈值', { exact: true })).toHaveValue('70')
})

test('启用前读取失败可恢复，旧窗口不能覆盖另一位操作者的启用选择', async ({ page }) => {
  const name = `模拟切换_${page.viewportSize()!.width}`
  await login(page, 'system_admin'); const first = await create(page, `${name}_甲`), second = await create(page, `${name}_乙`)
  await page.goto('/schemes'); await search(page, `${name}_甲`)
  await page.route(`**/api/hygiene/schemes/${first.id}`, route => route.abort('failed'))
  await page.getByRole('button', { name: '启用', exact: true }).click()
  const activation = page.getByRole('dialog', { name: '启用评分方案', exact: true })
  await expect(activation.getByRole('alert')).toContainText('暂时无法连接服务')
  await expect(activation.getByRole('button', { name: '确认启用', exact: true })).toBeDisabled()
  await page.unroute(`**/api/hygiene/schemes/${first.id}`)
  await activation.getByRole('button', { name: '刷新启用信息', exact: true }).click()
  await expect(activation.getByRole('button', { name: '确认启用', exact: true })).toBeEnabled()
  const current = await (await page.request.get('/api/hygiene/schemes?size=1')).json()
  expect((await post(page, `/api/hygiene/schemes/${second.id}/activate`, { version: 0, activeId: current.active?.id ?? 0 })).status()).toBe(200)
  await activation.getByRole('button', { name: '确认启用', exact: true }).click()
  await expect(activation.getByRole('alert')).toContainText('当前启用方案已变化')
  await expect(activation).toContainText(`${name}_甲`)
  await page.screenshot({ animations: 'disabled', path: `../output/playwright/task07-activate-conflict-${page.viewportSize()!.width}.png` })
  await activation.getByRole('button', { name: '刷新启用信息', exact: true }).click()
  await expect(activation).toContainText(`${name}_乙`)
  await activation.getByRole('button', { name: '确认启用', exact: true }).click(); await expect(activation).not.toBeVisible()
  await expect(page.getByTestId('active-scheme')).toContainText(`${name}_甲`)
})

