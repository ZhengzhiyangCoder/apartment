test('宿舍管理员只读住宿位置，学生和维修人员不可浏览住宿与学籍列表', async ({ page }) => {
  await login(page, 'dorm_manager')
  await page.getByRole('link', { name: '住宿管理', exact: true }).click()
  await expect(page.getByText('资料只读', { exact: true })).toBeVisible()
  await expect(page.getByRole('tab', { name: '学生资料', exact: true })).toHaveCount(0)
  for (const name of ['楼栋', '寝室', '床位']) {
    await page.getByRole('tab', { name, exact: true }).click()
    await expect(page.getByRole('button', { name: `新增${name}`, exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: '编辑', exact: true })).toHaveCount(0)
  }
  expect((await page.request.get('/api/housing/students')).status()).toBe(403)
  expect((await post(page, '/api/housing/buildings', { name: '越权创建' })).status()).toBe(403)
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登录栖居' })).toBeVisible()
  for (const role of ['student', 'maintainer']) {
    await login(page, role)
    await expect(page.getByRole('link', { name: '个人资料', exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: '住宿管理', exact: true })).toHaveCount(0)
    await page.goto('/housing')
    await expect(page.getByRole('heading', { name: '此页面暂不可访问' })).toBeVisible()
    expect((await page.request.get('/api/housing/rooms')).status()).toBe(403)
    expect((await page.request.get('/api/housing/students?userId=1')).status()).toBe(403)
    await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '登录栖居' })).toBeVisible()
  }
})

test('楼栋分页空页回退、父级分页选择和停用限制可操作', async ({ page }) => {
  const prefix = `分页楼栋 ${page.viewportSize()!.width} `
  await login(page)
  for (let i = 0; i < 11; i++) expect((await post(page, '/api/housing/buildings', { name: `${prefix}${i}` })).status()).toBe(201)
  await page.getByRole('link', { name: '住宿管理', exact: true }).click()
  await page.getByLabel('搜索资料').fill(prefix)
  await page.getByLabel('状态筛选').selectOption('true')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.getByRole('row')).toHaveCount(11)
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page.getByRole('row')).toHaveCount(2)
  const row = page.getByRole('row').filter({ hasText: `${prefix}0` })
  await row.getByRole('button', { name: '停用', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: '确认停用' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('row')).toHaveCount(11)
  await expect(page.getByRole('button', { name: '下一页', exact: true })).toBeDisabled()
  await page.getByRole('tab', { name: '寝室', exact: true }).click()
  await page.getByRole('button', { name: '新增寝室', exact: true }).click()
  await dialog.getByRole('button', { name: '下一组', exact: true }).click()
  await expect(dialog.locator('.picker-pages')).toContainText('2 /')
  await dialog.getByLabel('搜索所属楼栋').fill(prefix)
  await dialog.getByRole('button', { name: '查找', exact: true }).click()
  await dialog.getByLabel('所属楼栋', { exact: true }).selectOption({ label: `${prefix}1` })
  await dialog.getByLabel('房号', { exact: true }).fill('临时寝室')
  const building = (await (await page.request.get(`/api/housing/buildings?q=${encodeURIComponent(prefix + '1')}`)).json()).items.find((x: { name: string }) => x.name === `${prefix}1`)
  expect((await post(page, `/api/housing/buildings/${building.id}/enabled`, { enabled: false, version: building.version })).status()).toBe(200)
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('上级资料已停用')
  await expect(dialog.getByLabel('房号', { exact: true })).toHaveValue('临时寝室')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByLabel('搜索资料').fill('不存在的资料')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.getByText('暂无符合条件的寝室，请调整查询条件或新增资料。')).toBeVisible()
})
